#!/usr/bin/env bash
# 30-openwebui.sh - the browser interface where you (and your family) talk to
# the local models.
#
# Open WebUI is a container, so it does not need a GPU and can live on any
# machine in the house. It talks to Ollama over HTTP, which means it can be on
# a different PC from the model server entirely.

set -euo pipefail

AIORG_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../lib/common.sh
. "$AIORG_ROOT/lib/common.sh"
require_profile

COMPOSE_DIR="$AIORG_ROOT/compose/openwebui"
COMPOSE_FILE="$COMPOSE_DIR/docker-compose.yml"
OPENWEBUI_PORT="${AI_OPENWEBUI_PORT:-3000}"
OPENWEBUI_HOST="${AI_OPENWEBUI_BIND:-0.0.0.0}"

log_step "Setting up Open WebUI"

# Where the CONTAINER should look for Ollama, which is not the same as where
# this machine looks for it.
#
# AI_OLLAMA_URL is http://127.0.0.1:11434 in the default single-machine setup,
# and inside a container 127.0.0.1 is the container's own loopback. Ollama runs
# on the host, so the container was pointed at itself and could never reach a
# model - the UI came up, looked configured, and answered every chat with an
# error. When Ollama is local, the container has to go through
# host.docker.internal, which needs an explicit host-gateway mapping on Linux.
CONTAINER_OLLAMA_URL="$(aiorg_ollama_url)"
EXTRA_HOSTS_YAML=""
if aiorg_ollama_is_local; then
  CONTAINER_OLLAMA_URL="http://host.docker.internal:${AI_OLLAMA_PORT}"
  EXTRA_HOSTS_YAML='    extra_hosts:
      # Lets the container reach Ollama on the host. Without this,
      # host.docker.internal does not resolve on Linux.
      - "host.docker.internal:host-gateway"'
  log_dim "Ollama is on this machine."
  log_dim "  in the compose file it becomes: $CONTAINER_OLLAMA_URL"
  log_dim "  (127.0.0.1 inside a container is the container, not the host)"
else
  log_dim "Ollama is at ${AI_OLLAMA_HOST}, so the container can reach it directly."
fi

if ! command -v docker >/dev/null 2>&1; then
  log_warn "Docker is not installed. Skipping Open WebUI."
  log_dim "  Everything else works without it. Open WebUI is just the web UI -"
  log_dim "  your agents do not depend on it."
  log_dim ""
  log_dim "  To install Docker on Ubuntu/Debian:"
  log_dim "    curl -fsSL https://get.docker.com | sh"
  log_dim "    sudo usermod -aG docker \$USER    # then log out and back in"
  exit 0
fi

if ! docker info >/dev/null 2>&1; then
  log_err "Docker is installed but the daemon is not reachable."
  log_dim "  Try:  sudo systemctl start docker"
  exit 1
fi
log_ok "Docker is running."

mkdir -p "$COMPOSE_DIR"
mkdir -p "$AIORG_STATE/openwebui"

# The OLLAMA_BASE_URL is the important line: it tells the container where your
# model server is. If Ollama is on another PC, change AI_OLLAMA_HOST in
# config/profile.env (or export AI_OLLAMA_HOST before running bootstrap) and
# re-run this script.
cat > "$COMPOSE_FILE" <<EOF
# Generated by ai-org/scripts/30-openwebui.sh on $(date -Iseconds)
# Hardware tier at generation time: $AI_TIER
# Ollama endpoint: $AI_OLLAMA_URL
#
# This file is regenerated each time you run the script, so do not hand-edit
# it. Put your overrides in config/profile.env instead.

services:
  open-webui:
    image: ghcr.io/open-webui/open-webui:main
    container_name: ai-org-openwebui
    restart: unless-stopped
    ports:
      # Bound to $OPENWEBUI_HOST:$OPENWEBUI_PORT.
      # Change to 127.0.0.1 if you do not want it reachable from other PCs.
      - "${OPENWEBUI_HOST}:${OPENWEBUI_PORT}:8080"
    environment:
      # Where the models live. Ollama itself does NOT need to run in a
      # container - this just points at its HTTP API. This is the address the
      # CONTAINER can reach, which is not always AI_OLLAMA_URL.
      - OLLAMA_BASE_URL=$CONTAINER_OLLAMA_URL

      # First account created becomes the admin. Do this immediately.
      - WEBUI_AUTH=true

      # Let the models read local files. Turn this OFF if you want a
      # hard boundary between the chat UI and your filesystem.
      - ENABLE_CODE_INTERPRETER=true

      # Vector store for the document/RAG features. Kept on disk in
      # state/ so your indexed documents survive a container rebuild.
$EXTRA_HOSTS_YAML
    volumes:
      - $AIORG_STATE/openwebui:/app/backend/data
    # Ollama is reached over HTTP, so the container needs no /dev/nvidia.
    healthcheck:
      test: ["CMD-SHELL", "curl -sf http://localhost:8080/health || exit 1"]
      interval: 30s
      timeout: 5s
      retries: 5
EOF

log_step "Starting the container"
docker compose -f "$COMPOSE_FILE" up -d
log_ok "Started."

log_step "Waiting for it to become healthy (first start pulls a large image)"

for i in $(seq 1 60); do
  status="$(docker inspect -f '{{.State.Health.Status}}' ai-org-openwebui 2>/dev/null || echo "starting")"
  if [ "$status" = "healthy" ]; then
    log_ok "Healthy."
    break
  fi
  if [ "$status" = "unhealthy" ]; then
    log_err "Container reports unhealthy."
    log_dim "  docker logs --tail 50 ai-org-openwebui"
    exit 1
  fi
  # `docker compose up -d` just succeeded, so a container that is not there at
  # all is not going to turn up. Fail now rather than after 60 seconds of
  # polling for something that does not exist.
  if [ "$status" = "absent" ]; then
    log_err "Container does not exist, even though 'compose up' reported success."
    log_dim "  docker compose -f $COMPOSE_FILE ps"
    log_dim "  docker compose -f $COMPOSE_FILE up -d"
    exit 1
  fi
  [ $((i % 10)) -eq 0 ] && log_dim "  still starting (${i}s)..."
  sleep 1
done

# The loop can also expire with the container still pulling a large image, and
# the old code fell straight through to "Open WebUI is up." regardless. Re-read
# the state instead of assuming the loop's best outcome happened.
final_status="$(docker inspect -f '{{.State.Health.Status}}' ai-org-openwebui 2>/dev/null || echo absent)"
if [ "$final_status" != "healthy" ]; then
  log_err "Container did not become healthy (state: $final_status)."
  log_dim "  It may still be pulling a large image - that can take a few"
  log_dim "  minutes on a slow connection. Check with:"
  log_dim "    docker logs --tail 50 ai-org-openwebui"
  log_dim "    docker inspect -f '{{.State.Health.Status}}' ai-org-openwebui"
  log_dim "  Then re-run:  ./bootstrap.sh ui"
  exit 1
fi

IP="$(hostname -I 2>/dev/null | awk '{print $1}' || echo 'localhost')"
echo
log_ok "Open WebUI is up."
echo
log_dim "  On this machine:  http://localhost:${OPENWEBUI_PORT}"
log_dim "  From another PC:  http://${IP}:${OPENWEBUI_PORT}"
echo
log_warn "The FIRST account you create becomes the administrator."
log_dim "  Create it now, before anyone else can reach the URL."
echo
log_dim "  Stop it:    docker compose -f $COMPOSE_FILE down"
log_dim "  View logs:  docker logs -f ai-org-openwebui"
echo
